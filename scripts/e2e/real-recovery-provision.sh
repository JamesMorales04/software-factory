#!/usr/bin/env bash
# Narrow, auditable credential provisioning for the real gen2 recovery scenario.
#
# Development/UAT only. It does not start inference and does not run the
# scenario. It copies exactly two pieces of cryptographic material into a NEW
# disposable project so Core can decrypt the already-configured OpenCode Go
# credential:
#
#   1. the single `provider_settings` row for `opencode-go` (ciphertext, nonce
#      and fingerprint; no plaintext, no other provider, no other table);
#   2. the Core `master.key` file, volume-to-volume, mode 0600.
#
# Destination operator/reviewer tokens and remaining keys are generated by the
# canonical `factory-compose-init` service; no product token is copied. Source
# volumes are opened read-only and are never modified.
#
# Usage:
#   scripts/e2e/real-recovery-provision.sh --check   # plan + source preflight
#   scripts/e2e/real-recovery-provision.sh --apply   # create the disposable copy
#
# Environment:
#   FACTORY_RECOVERY_PROJECT              required, must contain "recovery" or "uat"
#   FACTORY_RECOVERY_ROOT                 repo root (default: this repository)
#   FACTORY_RECOVERY_RUN_ROOT             default /tmp/opencode/real-recovery-provision
#   FACTORY_RECOVERY_SOURCE_DATA_VOLUME   default software-factory_factory-data
#   FACTORY_RECOVERY_SOURCE_CONFIG_VOLUME default software-factory_factory-config-core
#
# Never prints secrets, ciphertext or tokens.

set -euo pipefail
set +x
umask 077

SOURCE_DATA_VOLUME=${FACTORY_RECOVERY_SOURCE_DATA_VOLUME:-software-factory_factory-data}
SOURCE_CONFIG_VOLUME=${FACTORY_RECOVERY_SOURCE_CONFIG_VOLUME:-software-factory_factory-config-core}
PROJECT=${FACTORY_RECOVERY_PROJECT:-}
ROOT=${FACTORY_RECOVERY_ROOT:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}
RUN_ROOT=${FACTORY_RECOVERY_RUN_ROOT:-/tmp/opencode/real-recovery-provision}
PROVIDER=opencode-go
MODEL=deepseek-v4.1-flash
BASE_URL=https://opencode.ai/inference/go/openai/v1

MODE=${1:-}
case "$MODE" in
  --check|--apply) ;;
  "") MODE=--check ;;
  *) echo "usage: $0 [--check|--apply]" >&2; exit 2 ;;
esac

fail() { echo "provisioning refused: $*" >&2; exit 1; }
compose() { podman compose -p "$PROJECT" -f "$ROOT/compose.yaml" -f "$ROOT/compose.real-provider-uat.yaml" "$@"; }

[[ -n "$PROJECT" ]] || fail "FACTORY_RECOVERY_PROJECT is required"
[[ "$PROJECT" != "software-factory" ]] || fail "refusing to provision the installed product project"
[[ "$PROJECT" == *recovery* || "$PROJECT" == *uat* ]] || fail "the project must contain 'recovery' or 'uat'"
[[ "$RUN_ROOT" == /* && "$RUN_ROOT" == *real-recovery* ]] || fail "FACTORY_RECOVERY_RUN_ROOT must be absolute and contain real-recovery"
[[ -f "$ROOT/compose.yaml" && -f "$ROOT/compose.real-provider-uat.yaml" ]] || fail "compose files are missing under $ROOT"
podman volume exists "$SOURCE_DATA_VOLUME" || fail "source data volume missing"
podman volume exists "$SOURCE_CONFIG_VOLUME" || fail "source config volume missing"

DATA_VOLUME="${PROJECT}_factory-data"
CONFIG_VOLUME="${PROJECT}_factory-config-core"
OPERATOR_TOKEN="$RUN_ROOT/operator.token"

TMP=$(mktemp -d "$RUN_ROOT/tmp.XXXXXX")
cleanup() { rm -rf "$TMP"; }
trap cleanup EXIT

mkdir -p "$RUN_ROOT"
chmod 700 "$RUN_ROOT"

readonly INSERT_COLUMNS="provider,kind,model,base_url,auth_mode,credential_ciphertext,credential_nonce,credential_fingerprint,enabled,is_default,max_turns,max_input_tokens,max_output_tokens,max_cost_micros,input_micros_per_million,output_micros_per_million,revision,updated_at"

# --- source preflight (read-only) -------------------------------------------
podman volume export "$SOURCE_DATA_VOLUME" -o "$TMP/source-data.tar"
tar -xf "$TMP/source-data.tar" -C "$TMP" factory.sqlite
chmod 600 "$TMP/factory.sqlite"
mv "$TMP/factory.sqlite" "$TMP/source.sqlite"

ROWS=$(sqlite3 "file:$TMP/source.sqlite?mode=ro" "SELECT count(*) FROM provider_settings WHERE provider='$PROVIDER';")
[[ "$ROWS" == "1" ]] || fail "source provider_settings must contain exactly one $PROVIDER row (found $ROWS)"
ROUTE=$(sqlite3 "file:$TMP/source.sqlite?mode=ro" "SELECT model || '|' || base_url || '|' || enabled || '|' || is_default || '|' || (length(credential_ciphertext)>0) || '|' || (length(credential_fingerprint)>0) FROM provider_settings WHERE provider='$PROVIDER';")
IFS='|' read -r SRC_MODEL SRC_URL SRC_ENABLED SRC_DEFAULT SRC_CIPHER SRC_FINGER <<<"$ROUTE"
[[ "$SRC_MODEL" == "$MODEL" ]] || fail "source model is not $MODEL"
[[ "$SRC_URL" == "$BASE_URL" ]] || fail "source base URL differs from the authorized route"
[[ "$SRC_ENABLED" == "1" && "$SRC_DEFAULT" == "1" ]] || fail "source provider is not enabled/default"
[[ "$SRC_CIPHER" == "1" && "$SRC_FINGER" == "1" ]] || fail "source provider has no encrypted credential"
sqlite3 "file:$TMP/source.sqlite?mode=ro" "PRAGMA integrity_check;" | grep -qx "ok" || fail "source DB integrity check failed"

podman volume export "$SOURCE_CONFIG_VOLUME" -o "$TMP/source-config.tar"
tar -xOf "$TMP/source-config.tar" master.key >"$TMP/master.key.raw"
chmod 600 "$TMP/master.key.raw"
tr -d '\r\n' <"$TMP/master.key.raw" >"$TMP/master.key"
chmod 600 "$TMP/master.key"
[[ "$(wc -c <"$TMP/master.key")" == "64" ]] || fail "master.key is not 64 hex characters"
grep -Eq '^[0-9a-f]{64}$' "$TMP/master.key" || fail "master.key is not lowercase hex"

echo "source preflight: one $PROVIDER row, enabled/default, encrypted credential present, master.key 64 hex, integrity ok"

if [[ "$MODE" == "--check" ]]; then
  cat <<EOF
check plan:
  target project:  $PROJECT
  target volumes:  $DATA_VOLUME, $CONFIG_VOLUME
  copy:            provider_settings($PROVIDER) one row + master.key (0600, opaque)
  generate:        operator/reviewer/verifier tokens and remaining keys via factory-compose-init
  never copied:    product DB/config, product operator/reviewer/master identity, other providers/tables
  source:          read-only; never modified
  next:            re-run with --apply after review
EOF
  exit 0
fi

# --- destination volumes -----------------------------------------------------
podman volume exists "$DATA_VOLUME" && fail "destination data volume already exists; remove only the disposable copy first"
podman volume exists "$CONFIG_VOLUME" && fail "destination config volume already exists; remove only the disposable copy first"
podman volume create "$DATA_VOLUME" >/dev/null
podman volume create "$CONFIG_VOLUME" >/dev/null

# Opaque master.key transfer, volume-to-volume, 0600.
mkdir -p "$TMP/config"
cp "$TMP/master.key" "$TMP/config/master.key"
chmod 600 "$TMP/config/master.key"
tar -C "$TMP/config" -cf "$TMP/master-config.tar" master.key
podman volume import "$CONFIG_VOLUME" "$TMP/master-config.tar"

# --- canonical initialization + migrations ----------------------------------
# factory-compose-init generates destination tokens/keys because they are
# absent; the pre-installed master.key is preserved for credential decryption.
compose up -d init core
for _ in $(seq 1 60); do
  CORE=$(podman ps --filter "label=com.docker.compose.project=$PROJECT" --filter 'label=com.docker.compose.service=core' --format '{{.Names}}' | head -1)
  [[ -n "$CORE" ]] && break
  sleep 1
done
[[ -n "${CORE:-}" ]] || fail "Core container did not start"
for _ in $(seq 1 120); do
  if podman exec "$CORE" curl -fsS --max-time 5 -H 'Host: localhost:8765' http://core-control:8765/health >/dev/null 2>&1; then
    break
  fi
  sleep 1
done
compose stop core >/dev/null

# Extract the migrated destination data volume and insert the single row.
podman volume export "$DATA_VOLUME" -o "$TMP/target-data.tar"
mkdir -p "$TMP/target"
tar -xf "$TMP/target-data.tar" -C "$TMP/target"
rm -f "$TMP/target/factory.sqlite-wal" "$TMP/target/factory.sqlite-shm"
chmod 600 "$TMP/target/factory.sqlite" 2>/dev/null || true

# Exact allowlist: one provider row, no other table, no audit rows.
sqlite3 "$TMP/target/factory.sqlite" <<SQL
ATTACH DATABASE '$TMP/source.sqlite' AS src;
INSERT INTO provider_settings ($INSERT_COLUMNS)
SELECT $INSERT_COLUMNS FROM src.provider_settings WHERE provider='$PROVIDER';
PRAGMA integrity_check;
SQL

rm -rf "$TMP/target-final"
mv "$TMP/target" "$TMP/target-final"
tar -C "$TMP/target-final" -cf "$TMP/target-data-updated.tar" .
podman volume rm "$DATA_VOLUME" >/dev/null
podman volume create "$DATA_VOLUME" >/dev/null
podman volume import "$DATA_VOLUME" "$TMP/target-data-updated.tar"

# --- start and preflight -----------------------------------------------------
compose up -d
CORE=$(podman ps --filter "label=com.docker.compose.project=$PROJECT" --filter 'label=com.docker.compose.service=core' --format '{{.Names}}' | head -1)
[[ -n "$CORE" ]] || fail "Core container did not start"
for _ in $(seq 1 180); do
  if podman exec "$CORE" curl -fsS --max-time 5 -H 'Host: localhost:8765' http://core-control:8765/health >/dev/null 2>&1; then
    break
  fi
  sleep 1
done

podman exec "$CORE" cat /config/operator.token >"$OPERATOR_TOKEN"
chmod 600 "$OPERATOR_TOKEN"
[[ -s "$OPERATOR_TOKEN" ]] || fail "destination operator token is empty"

podman volume export "$DATA_VOLUME" -o "$TMP/verify-data.tar"
mkdir -p "$TMP/verify"
tar -xf "$TMP/verify-data.tar" -C "$TMP/verify"
VERIFY=$(sqlite3 "file:$TMP/verify/factory.sqlite?mode=ro" "SELECT count(*) || '|' || model || '|' || base_url || '|' || enabled || '|' || is_default || '|' || (length(credential_ciphertext)>0) || '|' || (length(credential_fingerprint)>0) FROM provider_settings WHERE provider='$PROVIDER';")
IFS='|' read -r V_COUNT V_MODEL V_URL V_ENABLED V_DEFAULT V_CIPHER V_FINGER <<<"$VERIFY"
[[ "$V_COUNT" == "1" && "$V_MODEL" == "$MODEL" && "$V_URL" == "$BASE_URL" && "$V_ENABLED" == "1" && "$V_DEFAULT" == "1" && "$V_CIPHER" == "1" && "$V_FINGER" == "1" ]] || fail "destination provider preflight failed"
sqlite3 "file:$TMP/verify/factory.sqlite?mode=ro" "PRAGMA integrity_check;" | grep -qx "ok" || fail "destination DB integrity check failed"
PLAINTEXT_COLUMNS=$(sqlite3 "file:$TMP/verify/factory.sqlite?mode=ro" "SELECT count(*) FROM pragma_table_info('provider_settings') WHERE name IN ('credential_plaintext','api_key','plaintext','secret');")
[[ "$PLAINTEXT_COLUMNS" == "0" ]] || fail "provider_settings unexpectedly exposes a plaintext credential column"

LEAD_FIXTURE=$(compose config | awk '/FACTORY_LEAD_FIXTURE_ASSESSOR:/ {print $2; exit}')
[[ "$LEAD_FIXTURE" == "\"0\"" || "$LEAD_FIXTURE" == "0" ]] || fail "FACTORY_LEAD_FIXTURE_ASSESSOR must be 0 for the real route"

echo "destination preflight: one $PROVIDER row, enabled/default, encrypted credential present, no plaintext column, integrity ok"
echo "disposable stack ready: project=$PROJECT operator_token=$OPERATOR_TOKEN"
echo "source volumes unchanged. Remove the disposable copy with:"
echo "  podman compose -p $PROJECT -f $ROOT/compose.yaml -f $ROOT/compose.real-provider-uat.yaml down -v"
