#!/usr/bin/env bash
# Narrow, auditable credential provisioning for the real gen2 recovery scenario.
#
# Development/UAT only. It does not start inference and does not run the
# scenario. It copies exactly two pieces of cryptographic material into a NEW
# disposable project so Core can decrypt the already-configured OpenCode Go
# credential:
#
#   1. the single `provider_settings` row for `opencode-go` (ciphertext, nonce
#      and fingerprint; no plaintext, no other provider, no other table);
#   2. the Core `master.key` file, volume-to-volume, mode 0600.
#
# The source volumes are mounted READ-ONLY into a short-lived tool container.
# There is no whole-volume export, no host copy of the database or config, no
# tar of the source, and no WAL/SHM deletion: the row copy uses SQLite ATTACH
# and a WAL checkpoint. Destination operator/reviewer tokens are generated by
# factory-compose-init; no product token is copied.
#
# Usage:
#   scripts/e2e/real-recovery-provision.sh --check   # read-only source preflight
#   scripts/e2e/real-recovery-provision.sh --apply   # create the disposable copy
#
# Environment:
#   FACTORY_RECOVERY_PROJECT              required, must contain "recovery" or "uat"
#   FACTORY_RECOVERY_ROOT                 repo root (default: this repository)
#   FACTORY_RECOVERY_RUN_ROOT             default /tmp/opencode/real-recovery-provision
#   FACTORY_RECOVERY_SOURCE_DATA_VOLUME   default software-factory_factory-data
#   FACTORY_RECOVERY_SOURCE_CONFIG_VOLUME default software-factory_factory-config-core
#   FACTORY_RECOVERY_TOOL_IMAGE           default localhost/software-factory-dev:local
#
# Never prints secrets, ciphertext or tokens.

set -euo pipefail
set +x
umask 077

SOURCE_DATA_VOLUME=${FACTORY_RECOVERY_SOURCE_DATA_VOLUME:-software-factory_factory-data}
SOURCE_CONFIG_VOLUME=${FACTORY_RECOVERY_SOURCE_CONFIG_VOLUME:-software-factory_factory-config-core}
PROJECT=${FACTORY_RECOVERY_PROJECT:-}
ROOT=${FACTORY_RECOVERY_ROOT:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}
RUN_ROOT=${FACTORY_RECOVERY_RUN_ROOT:-/tmp/opencode/real-recovery-provision}
TOOL_IMAGE=${FACTORY_RECOVERY_TOOL_IMAGE:-localhost/software-factory-dev:local}
PROVIDER=opencode-go
MODEL=deepseek-v4.1-flash
BASE_URL=https://opencode.ai/inference/go/openai/v1
TOOL_USER=10001:10001

MODE=${1:-}
case "$MODE" in
  --check|--apply) ;;
  "") MODE=--check ;;
  *) echo "usage: $0 [--check|--apply]" >&2; exit 2 ;;
esac

fail() { echo "provisioning refused: $*" >&2; exit 1; }
compose() { podman compose -p "$PROJECT" -f "$ROOT/compose.yaml" -f "$ROOT/compose.real-provider-uat.yaml" "$@"; }

[[ -n "$PROJECT" ]] || fail "FACTORY_RECOVERY_PROJECT is required"
[[ "$PROJECT" != "software-factory" ]] || fail "refusing to provision the installed product project"
[[ "$PROJECT" == *recovery* || "$PROJECT" == *uat* ]] || fail "the project must contain 'recovery' or 'uat'"
[[ "$RUN_ROOT" == /* && "$RUN_ROOT" == *real-recovery* ]] || fail "FACTORY_RECOVERY_RUN_ROOT must be absolute and contain real-recovery"
[[ -f "$ROOT/compose.yaml" && -f "$ROOT/compose.real-provider-uat.yaml" ]] || fail "compose files are missing under $ROOT"
podman volume exists "$SOURCE_DATA_VOLUME" || fail "source data volume missing"
podman volume exists "$SOURCE_CONFIG_VOLUME" || fail "source config volume missing"
podman image exists "$TOOL_IMAGE" || fail "tool image $TOOL_IMAGE is missing"

# The read-only source snapshot is opened with SQLite `immutable=1`, which does
# not consult `-wal`. That is only sound while the source project is quiescent.
SOURCE_PROJECT=${SOURCE_DATA_VOLUME%_factory-data}
ACTIVE_SOURCE=$(podman ps --filter "label=com.docker.compose.project=$SOURCE_PROJECT" --format '{{.Names}}' | tr '\n' ' ')
[[ -z "$ACTIVE_SOURCE" ]] || fail "source project $SOURCE_PROJECT is running ($ACTIVE_SOURCE); stop it so the read-only snapshot is consistent"

DATA_VOLUME="${PROJECT}_factory-data"
CONFIG_VOLUME="${PROJECT}_factory-config-core"
OPERATOR_TOKEN="$RUN_ROOT/operator.token"

mkdir -p "$RUN_ROOT"
chmod 700 "$RUN_ROOT"

readonly INSERT_COLUMNS="provider,kind,model,base_url,auth_mode,credential_ciphertext,credential_nonce,credential_fingerprint,enabled,is_default,max_turns,max_input_tokens,max_output_tokens,max_cost_micros,input_micros_per_million,output_micros_per_million,revision,updated_at"

# --- source preflight (read-only, in-container, no host copies) -------------
SOURCE_CHECK=$(podman run --rm -i --user "$TOOL_USER" \
  -v "$SOURCE_DATA_VOLUME:/src-data:ro" \
  -v "$SOURCE_CONFIG_VOLUME:/src-config:ro" \
  "$TOOL_IMAGE" python3 - <<'PY'
import re
import sqlite3
import sys

db = sqlite3.connect("file:/src-data/factory.sqlite?mode=ro&immutable=1", uri=True)
rows = db.execute(
    "SELECT model,base_url,enabled,is_default,length(credential_ciphertext),"
    "length(credential_fingerprint) FROM provider_settings WHERE provider='opencode-go'"
).fetchall()
if len(rows) != 1:
    print(f"SOURCE_ROW_COUNT={len(rows)}")
    sys.exit(1)
model, base_url, enabled, is_default, cipher, finger = rows[0]
key = open("/src-config/master.key", encoding="utf-8").read().strip()
if not re.fullmatch(r"[0-9a-f]{64}", key):
    print("MASTER_KEY_INVALID")
    sys.exit(1)
integrity = db.execute("PRAGMA integrity_check").fetchone()[0]
if model != "deepseek-v4.1-flash" or base_url != "https://opencode.ai/inference/go/openai/v1":
    print("SOURCE_ROUTE_MISMATCH")
    sys.exit(1)
if enabled != 1 or is_default != 1 or not cipher or not finger:
    print("SOURCE_PROVIDER_STATE_INVALID")
    sys.exit(1)
if integrity != "ok":
    print("SOURCE_INTEGRITY_FAILED")
    sys.exit(1)
print("SOURCE_CHECK_OK one opencode-go row, enabled/default, ciphertext+fingerprint present, master.key 64 hex, integrity ok")
PY
) || fail "source preflight failed"
echo "$SOURCE_CHECK"

if [[ "$MODE" == "--check" ]]; then
  cat <<EOF
check plan:
  target project:  $PROJECT
  target volumes:  $DATA_VOLUME, $CONFIG_VOLUME
  copy:            provider_settings($PROVIDER) one row + master.key (0600, opaque)
  method:          read-only source mounts + in-container SQLite ATTACH + WAL checkpoint
  generate:        operator/reviewer/verifier tokens and remaining keys via factory-compose-init
  never copied:    product DB/config files, product operator/reviewer/master identity, other providers/tables
  source:          read-only; never modified; no host export/tar
  next:            re-run with --apply after review
EOF
  exit 0
fi

podman volume exists "$DATA_VOLUME" && fail "destination data volume already exists; remove only the disposable copy first"
podman volume exists "$CONFIG_VOLUME" && fail "destination config volume already exists; remove only the disposable copy first"
podman volume create "$DATA_VOLUME" >/dev/null
podman volume create "$CONFIG_VOLUME" >/dev/null

# Opaque master.key transfer, volume-to-volume, 0600, no host copy.
podman run --rm -i --user "$TOOL_USER" \
  -v "$SOURCE_CONFIG_VOLUME:/src-config:ro" \
  -v "$CONFIG_VOLUME:/dst-config" \
  "$TOOL_IMAGE" sh -c 'install -m 0600 /src-config/master.key /dst-config/master.key'

# --- canonical initialization + migrations ----------------------------------
compose up -d init core
CORE=""
for _ in $(seq 1 60); do
  CORE=$(podman ps --filter "label=com.docker.compose.project=$PROJECT" --filter 'label=com.docker.compose.service=core' --format '{{.Names}}' | head -1)
  [[ -n "$CORE" ]] && break
  sleep 1
done
[[ -n "$CORE" ]] || fail "Core container did not start"
for _ in $(seq 1 120); do
  if podman exec "$CORE" curl -fsS --max-time 5 -H 'Host: localhost:8765' http://core-control:8765/health >/dev/null 2>&1; then
    break
  fi
  sleep 1
done
compose stop core >/dev/null

# Copy exactly one row into the migrated destination DB with SQLite ATTACH.
podman run --rm -i --user "$TOOL_USER" \
  -v "$SOURCE_DATA_VOLUME:/src-data:ro" \
  -v "$DATA_VOLUME:/dst-data" \
  "$TOOL_IMAGE" python3 - "$INSERT_COLUMNS" <<'PY'
import sqlite3
import sys

columns = [column for column in sys.argv[1].split(",") if column]
source = sqlite3.connect("file:/src-data/factory.sqlite?mode=ro&immutable=1", uri=True)
row = source.execute(
    f"SELECT {','.join(columns)} FROM provider_settings WHERE provider='opencode-go'"
).fetchone()
if row is None:
    print("SOURCE_ROW_MISSING")
    sys.exit(1)
destination = sqlite3.connect("/dst-data/factory.sqlite")
placeholders = ",".join("?" for _ in columns)
destination.execute(
    f"INSERT INTO provider_settings ({','.join(columns)}) VALUES ({placeholders})", row
)
destination.commit()
# Consistent checkpoint instead of deleting WAL/SHM files.
result = destination.execute("PRAGMA wal_checkpoint(TRUNCATE)").fetchone()
integrity = destination.execute("PRAGMA integrity_check").fetchone()[0]
if integrity != "ok":
    print("DEST_INTEGRITY_FAILED", integrity)
    sys.exit(1)
print("ROW_COPY_OK", result[0])
PY

# --- start and preflight -----------------------------------------------------
compose up -d
CORE=$(podman ps --filter "label=com.docker.compose.project=$PROJECT" --filter 'label=com.docker.compose.service=core' --format '{{.Names}}' | head -1)
[[ -n "$CORE" ]] || fail "Core container did not start"
for _ in $(seq 1 180); do
  if podman exec "$CORE" curl -fsS --max-time 5 -H 'Host: localhost:8765' http://core-control:8765/health >/dev/null 2>&1; then
    break
  fi
  sleep 1
done

podman exec "$CORE" cat /config/operator.token >"$OPERATOR_TOKEN"
chmod 600 "$OPERATOR_TOKEN"
[[ -s "$OPERATOR_TOKEN" ]] || fail "destination operator token is empty"

podman run --rm -i --user "$TOOL_USER" -v "$DATA_VOLUME:/dst-data:ro" "$TOOL_IMAGE" python3 - <<'PY' || fail "destination preflight failed"
import sqlite3
import sys

db = sqlite3.connect("file:/dst-data/factory.sqlite?mode=ro&immutable=1", uri=True)
rows = db.execute(
    "SELECT count(*),model,base_url,enabled,is_default,length(credential_ciphertext),"
    "length(credential_fingerprint) FROM provider_settings WHERE provider='opencode-go'"
).fetchone()
count, model, base_url, enabled, is_default, cipher, finger = rows
plaintext = db.execute(
    "SELECT count(*) FROM pragma_table_info('provider_settings') WHERE name IN "
    "('credential_plaintext','api_key','plaintext','secret')"
).fetchone()[0]
integrity = db.execute("PRAGMA integrity_check").fetchone()[0]
ok = (
    count == 1 and model == "deepseek-v4.1-flash"
    and base_url == "https://opencode.ai/inference/go/openai/v1"
    and enabled == 1 and is_default == 1 and bool(cipher) and bool(finger)
    and plaintext == 0 and integrity == "ok"
)
if not ok:
    print("DEST_PREFLIGHT_INVALID")
    sys.exit(1)
print("DEST_CHECK_OK one opencode-go row, enabled/default, ciphertext present, no plaintext column, integrity ok")
PY

LEAD_FIXTURE=$(compose config | awk '/FACTORY_LEAD_FIXTURE_ASSESSOR:/ {print $2; exit}')
[[ "$LEAD_FIXTURE" == "\"0\"" || "$LEAD_FIXTURE" == "0" ]] || fail "FACTORY_LEAD_FIXTURE_ASSESSOR must be 0 for the real route"

echo "disposable stack ready: project=$PROJECT operator_token=$OPERATOR_TOKEN"
echo "source volumes unchanged. Remove the disposable copy with:"
echo "  podman compose -p $PROJECT -f $ROOT/compose.yaml -f $ROOT/compose.real-provider-uat.yaml down -v"
